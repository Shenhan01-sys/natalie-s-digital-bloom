// Generates the SQL that loads the static portfolio content into Supabase.
// Usage: npx tsx scripts/content-to-sql.ts > supabase/migrations/<ts>_content.sql (already applied: 20261011034334)
import { defaultContent as c, shopLinks, shopSettings } from "../src/data/content";

const q = (v: unknown) => `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
const rows: string[] = [];
const add = (section: string, items: unknown[]) =>
  items.forEach((data, i) => rows.push(`  ('${section}', ${q(data)}, ${i})`));

add("education", c.education);
add("experience", c.experience);
add("language", c.languages.map((name) => ({ name })));
add("software", c.software);
add("client", c.clients.map((name) => ({ name })));
add("contact", c.contacts);
add("category", c.categories.map(({ id, note }) => ({ name: id, note })));
add("work", c.works.map(({ id: _id, ...w }) => w));
add("shop_link", shopLinks);

console.log(`-- Generated by scripts/content-to-sql.ts from src/data/content.ts
insert into public.site_settings (key, value) values
  ('profile', ${q(c.profile)}),
  ('shop', ${q(shopSettings)})
on conflict (key) do nothing;

insert into public.content_items (section, data, sort)
select v.section, v.data, v.sort from (values
${rows.join(",\n")}
) as v(section, data, sort)
where not exists (select 1 from public.content_items);`);
